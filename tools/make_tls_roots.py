#!/usr/bin/env python3
"""Pack assets/tls/roots.pem into src/tls_roots.h, an ESP-IDF certificate bundle.

The bundle (format of ESP-IDF's gen_crt_bundle.py, read by WiFiClientSecure::
setCACertBundle) keeps only each root's subject name and public key, sorted by
subject: about 400 bytes per root in flash, and at a handshake only the root
that signed the server's chain is parsed. Standard library only.

    python3 tools/make_tls_roots.py           # write src/tls_roots.h
    python3 tools/make_tls_roots.py --check   # fail if it is out of date
"""
from pathlib import Path
import argparse
import base64
import datetime
import re
import struct
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/tls/roots.pem'
OUTPUT = ROOT / 'src/tls_roots.h'


def tlv(data, at):
    """(tag, start of value, end of value, end of element) of the DER element at `at`."""
    tag, length = data[at], data[at + 1]
    at += 2
    if length & 0x80:
        count = length & 0x7f
        if not 1 <= count <= 3:
            raise ValueError('unsupported DER length')
        length = int.from_bytes(data[at:at + count], 'big')
        at += count
    if at + length > len(data):
        raise ValueError('truncated DER element')
    return tag, at, at + length, at + length


def der_time(tag, value):
    text = value.decode('ascii')
    if tag == 0x17:  # UTCTime, YYMMDDHHMMSSZ
        year = int(text[:2])
        text = ('19' if year >= 50 else '20') + text
    return datetime.datetime.strptime(text, '%Y%m%d%H%M%SZ').replace(tzinfo=datetime.timezone.utc)


def parse(der):
    """Subject Name and SubjectPublicKeyInfo (raw DER, as in the bundle) and notAfter."""
    tag, start, end, _ = tlv(der, 0)
    if tag != 0x30:
        raise ValueError('not a certificate')
    tag, at, tbs_end, _ = tlv(der, start)
    if tag != 0x30:
        raise ValueError('no tbsCertificate')
    fields = []
    while at < tbs_end:
        tag, value, value_end, element_end = tlv(der, at)
        fields.append((tag, at, value, value_end, element_end))
        at = element_end
    if fields[0][0] == 0xa0:  # explicit version
        fields = fields[1:]
    # serialNumber, signature, issuer, validity, subject, subjectPublicKeyInfo
    validity, subject, key = fields[3], fields[4], fields[5]
    if validity[0] != 0x30 or subject[0] != 0x30 or key[0] != 0x30:
        raise ValueError('unexpected certificate layout')
    _, not_before_value, _, after_start = tlv(der, validity[2])
    after_tag, after_value, after_end, _ = tlv(der, after_start)
    expires = der_time(after_tag, der[after_value:after_end])
    return der[subject[1]:subject[4]], der[key[1]:key[4]], expires


def certificates(text):
    """(label, DER) of every PEM block; the label is the comment line just above it."""
    pattern = r'(?:^# ([^\n]*)\n)?-----BEGIN CERTIFICATE-----\n([A-Za-z0-9+/=\s]*?)-----END CERTIFICATE-----'
    return [(block.group(1) or '', base64.b64decode(''.join(block.group(2).split()), validate=True))
            for block in re.finditer(pattern, text, re.M)]


def bundle(roots):
    entries = sorted((name, key) for name, key in roots)
    names = [name for name, _ in entries]
    if len(set(names)) != len(names):
        raise ValueError('two roots with the same subject: the bundle lookup is by subject')
    out = bytearray(struct.pack('>H', len(entries)))
    for name, key in entries:
        out += struct.pack('>HH', len(name), len(key)) + name + key
    return bytes(out)


def bundle_v2(roots):
    """The format of ESP-IDF 5.4 and later (gen_crt_bundle.py): a little-endian
    uint32 offset per root, then each root as little-endian name and key
    lengths, subject name and public key, sorted by subject."""
    entries = sorted((name, key) for name, key in roots)
    names = [name for name, _ in entries]
    if len(set(names)) != len(names):
        raise ValueError('two roots with the same subject: the bundle lookup is by subject')
    body, offsets = bytearray(), []
    for name, key in entries:
        offsets.append(4 * len(entries) + len(body))
        body += struct.pack('<HH', len(name), len(key)) + name + key
    return struct.pack('<%dL' % len(offsets), *offsets) + bytes(body)


def array(data):
    lines = [f'static const uint8_t kTlsRootBundle[{len(data)}] = {{']
    for at in range(0, len(data), 20):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[at:at + 20]) + ',')
    return lines + ['};']


def header(data, data_v2, labels):
    lines = ['// Generated by tools/make_tls_roots.py from assets/tls/roots.pem: do not edit.',
             '// ESP-IDF certificate bundle (subject name + public key of each trusted root,',
             '// sorted by subject) for WiFiClientSecure::setCACertBundle().',
             '// ' + str(len(labels)) + ' roots: ' + ', '.join(labels) + '.',
             '#pragma once', '#include <stdint.h>',
             '#if __has_include(<esp_idf_version.h>)', '#include <esp_idf_version.h>', '#endif',
             '#if defined(ESP_IDF_VERSION) && ESP_IDF_VERSION >= ESP_IDF_VERSION_VAL(5, 4, 0)',
             '// ESP-IDF 5.4 and later: a little-endian offset table, then little-endian lengths.',
             *array(data_v2),
             '#else',
             '// ESP-IDF up to 5.3: a big-endian count, then big-endian lengths.',
             *array(data),
             '#endif']
    # Wrap the long root list comment at word boundaries.
    wrapped = []
    for line in lines:
        while len(line) > 110 and line.startswith('// '):
            cut = line.rfind(', ', 0, 108) + 1
            wrapped.append(line[:cut])
            line = '//  ' + line[cut:].lstrip()
        wrapped.append(line)
    return '\n'.join(wrapped) + '\n'


def build(text):
    parsed = [(re.sub(r' \((?:current|legacy)[^)]*\)$', '', label), *parse(der)) for label, der in certificates(text)]
    if not parsed:
        raise ValueError('no certificate found')
    roots = [(name, key) for _, name, key, _ in parsed]
    return header(bundle(roots), bundle_v2(roots), [label for label, *_ in parsed])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if src/tls_roots.h is out of date')
    args = parser.parse_args()
    generated = build(SOURCE.read_text())
    if args.check:
        if OUTPUT.read_text() != generated:
            sys.exit('src/tls_roots.h is out of date: run python3 tools/make_tls_roots.py')
        return
    OUTPUT.write_text(generated)
    print(f'{OUTPUT.relative_to(ROOT)}: {generated.count("0x")} bytes')


if __name__ == '__main__':
    main()
