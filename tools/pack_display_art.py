#!/usr/bin/env python3
"""Pack the original 2x2 illustration atlas into four 128x128 RGB565 images.
This is asset encoding, with no image decoder required on the miner.
Run manually after changing assets/display/illustrations.png. Pillow is only
needed for this preparation step, not normal firmware builds or native tests.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 128
NATIVE_SIZES = ((12, 17, 26, 31, 40), (31, 40), (31, 40), (23, 36))


def main():
    with Image.open(ROOT / "assets/display/illustrations.png") as source:
        source = source.convert("RGB")
        w, h = source.size
        assert w == h and w % 2 == 0, "Expected a square 2x2 atlas"
        images, native = [], []
        for i in range(4):
            x, y = i % 2 * (w // 2), i // 2 * (h // 2)
            original = source.crop((x, y, x + w // 2, y + h // 2))
            image = original.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
            data = image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata()
            images.append([(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r, g, b in data])
            for size in NATIVE_SIZES[i]:
                image = original.resize((size, size), Image.Resampling.LANCZOS)
                data = image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata()
                native.append((i, size, [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r, g, b in data]))
    text = "// Generated by tools/pack_display_art.py; original artwork in assets/display.\n#pragma once\n#include <stdint.h>\nnamespace ui_art {\n"
    text += f"constexpr int kArtworkSize = {SIZE};\nconstexpr uint16_t kArtwork[4][{SIZE * SIZE}] = {{\n"
    for pixels in images:
        text += "{\n" + "\n".join("    " + ",".join(f"0x{p:04x}" for p in pixels[i:i+16]) + "," for i in range(0, len(pixels), 16)) + "\n},\n"
    text += "};\n"
    for icon, size, pixels in native:
        text += f'constexpr uint16_t kNative{icon}_{size}[] = {{\n'
        text += '\n'.join('    ' + ','.join(f'0x{p:04x}' for p in pixels[i:i+16]) + ',' for i in range(0, len(pixels), 16)) + '\n};\n'
    text += 'struct NativeImage { uint8_t icon, size; const uint16_t *pixels; };\n'
    text += 'constexpr NativeImage kNativeImages[] = {\n' + ''.join(f'    {{{icon},{size},kNative{icon}_{size}}},\n' for icon, size, _ in native) + '};\n'
    text += '}  // namespace ui_art\n'
    (ROOT / "src/ui_art_data.h").write_text(text)
    print('Packed four 128x128 sources and native-size sprites:', 131072 + sum(len(pixels)*2 for _, _, pixels in native), 'bytes, no decoder buffer')


if __name__ == "__main__":
    main()
