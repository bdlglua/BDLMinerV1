#!/usr/bin/env python3
"""Pack the original 2x2 illustration atlas into four 64x64 RGB565 images.
This is asset encoding, with no image decoder required on the miner.
Run manually after changing assets/display/illustrations.png. Pillow is only
needed for this preparation step, not normal firmware builds or native tests.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 64


def main():
    with Image.open(ROOT / "assets/display/illustrations.png") as source:
        source = source.convert("RGB")
        w, h = source.size
        assert w == h and w % 2 == 0, "Expected a square 2x2 atlas"
        images = []
        for i in range(4):
            x, y = i % 2 * (w // 2), i // 2 * (h // 2)
            image = source.crop((x, y, x + w // 2, y + h // 2)).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
            data = image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata()
            images.append([(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r, g, b in data])
    text = "// Generated by tools/pack_display_art.py; original artwork in assets/display.\n#pragma once\n#include <stdint.h>\nnamespace ui_art {\n"
    text += f"constexpr int kArtworkSize = {SIZE};\nconstexpr uint16_t kArtwork[4][{SIZE * SIZE}] = {{\n"
    for pixels in images:
        text += "{\n" + "\n".join("    " + ",".join(f"0x{p:04x}" for p in pixels[i:i+16]) + "," for i in range(0, len(pixels), 16)) + "\n},\n"
    text += "};\n}  // namespace ui_art\n"
    (ROOT / "src/ui_art_data.h").write_text(text)
    print("Packed four 64x64 illustrations: 32 KiB of flash, no decoder buffer")


if __name__ == "__main__":
    main()
