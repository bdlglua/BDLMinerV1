#!/usr/bin/env python3
"""Pack the offline miner UI into deterministic, gzip-compressed flash assets."""
import gzip
import hashlib
import os
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ('common', 'dashboard', 'settings', 'log')


def generate(root=ROOT):
    root = Path(root)
    web = root / 'web'
    sources = [(name + '.js', (web / (name + '.js')).read_bytes()) for name in SCRIPTS]
    sources.append(('style.css', (web / 'style.css').read_bytes()))
    sources.append(('manifest.webmanifest', (web / 'manifest.webmanifest').read_bytes()))
    version = hashlib.sha256(b''.join(name.encode() + b'\0' + data for name, data in sources)).hexdigest()[:16]
    lines = ['// Generated by tools/make_web.py; edit web/ instead.', '#pragma once',
             'const char kWebVersion[] = "' + version + '";']
    for name, data in sources:
        symbol = 'kWeb' + name.split('.')[0].capitalize()
        packed = gzip.compress(data, compresslevel=9, mtime=0)
        lines.append('const uint8_t ' + symbol + '[] PROGMEM = {')
        lines.extend(' ' + ','.join(str(x) for x in packed[i:i + 24]) + ',' for i in range(0, len(packed), 24))
        lines.append('};')
    # PNGs are compressed already: stored as they are.
    for size in (192, 512):
        data = (web / ('icon-%d.png' % size)).read_bytes()
        lines.append('const uint8_t kWebIcon%d[] PROGMEM = {' % size)
        lines.extend(' ' + ','.join(str(x) for x in data[i:i + 24]) + ',' for i in range(0, len(data), 24))
        lines.append('};')
    for name, symbol in [('header', 'kHeader'), ('dashboard', 'kDashboard'),
                         ('settings', 'kSettingsPage'), ('log', 'kLogPage')]:
        html = (web / (name + '.html')).read_text(encoding='utf-8')
        if ')WEB"' in html:
            raise ValueError('Reserved C++ delimiter in ' + name)
        lines.append('const char ' + symbol + '[] PROGMEM = R"WEB(' + html + ')WEB";')
    output = root / 'src' / 'web_assets.generated.h'
    content = '\n'.join(lines) + '\n'
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        # Separate PlatformIO invocations can generate the same header. Never
        # expose a truncated file to a compiler or leave one after a failure.
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=output.parent, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(content)
            os.replace(temporary, output)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    return output


if __name__ == '__main__':
    print(generate())
