#!/usr/bin/env python3
"""Bake antialiased DejaVu Sans glyphs at native display sizes (Pillow only).
The firmware uses 4-bit coverage RLE directly from flash, without font loads,
glyph heap allocations or stretching a low-resolution bitmap font.
"""
from pathlib import Path
import argparse
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
# Text labels and messages stay small; the "big number" screens draw one
# value per page with the numeral faces, up to 80 px on 320x240 panels.
TEXT_SIZES = (8, 9, 10, 11, 12, 14, 16, 18, 20, 24)
NUMERAL_SIZES = (8, 9, 10, 11, 12, 14, 16, 18, 20, 24, 28, 32, 40, 48, 56, 64, 72, 80)
CHARS = ''.join(chr(i) for i in range(32, 127))
# Digits, separators and SI prefixes ("1.24T", "152.4T", "12.7k").
NUMERALS = ''.join(sorted(set('0123456789 .:-+%C?kMGTPEZ')))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, default=ROOT / 'assets/display/DejaVuSans.ttf')
    parser.add_argument('--bold-font', type=Path, default=ROOT / 'assets/display/DejaVuSans-Bold.ttf')
    args = parser.parse_args()
    glyphs, pixels, faces = [], [], []
    for numeric, height in [(False, h) for h in TEXT_SIZES] + [(True, h) for h in NUMERAL_SIZES]:
        charset = NUMERALS if numeric else CHARS
        # Small labels need solid stems on the LCD. Numerical faces use their
        # own cap-height bounds, so unused descenders no longer shrink digits.
        path = args.bold_font if height <= 12 else args.font
        size = height * 2 if numeric else height
        while True:
            font = ImageFont.truetype(str(path), size)
            _, top, _, bottom = font.getbbox(charset, anchor='ls')
            if bottom - top <= height - (1 if numeric else 0) or size == 1:
                break
            size -= 1
        baseline = -top + (height - (bottom - top)) // 2
        first = len(glyphs)
        for char in charset:
            left, _, right, _ = font.getbbox(char, anchor='ls')
            width = max(1, right - left)
            advance = max(1, math.ceil(font.getlength(char)))
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, baseline), char, font=font, fill=255, anchor='ls')
            data = image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()
            coverage = [(v * 15 + 127) // 255 for v in data]
            offset = len(pixels)
            for i in range(len(coverage)):
                if i and coverage[i] == coverage[i-1] and pixels[-1] >> 4 < 15:
                    pixels[-1] += 16
                else:
                    pixels.append(coverage[i])
            glyphs.append((offset, len(pixels) - offset, width, advance, left))
        faces.append((height, baseline, first, numeric))
    out = '// Generated by tools/pack_display_fonts.py; DejaVu license in assets/display/.\n#pragma once\n#include <stdint.h>\nnamespace ui_font {\n'
    out += 'struct Glyph { uint32_t offset; uint16_t length; uint8_t width, advance; int8_t left; };\n'
    out += 'constexpr Glyph kGlyphs[] = {\n' + ''.join('    {' + ','.join(map(str, g)) + '},\n' for g in glyphs) + '};\n'
    out += 'constexpr uint8_t kCoverage[] = {\n' + '\n'.join('    ' + ','.join(f'0x{v:02x}' for v in pixels[i:i+24]) + ',' for i in range(0, len(pixels), 24)) + '\n};\n'
    out += f'constexpr unsigned kTextFaces = {len(TEXT_SIZES)}, kNumeralFaces = {len(NUMERAL_SIZES)};\n'
    out += 'constexpr char kNumeralCharacters[] = "' + NUMERALS + '";\n'
    out += '#define BDL_FONT_FACES ' + ','.join('{' + str(first) + ',' + str(height) + ',' + str(baseline) + ',' + str(numeric).lower() + '}' for height, baseline, first, numeric in faces) + '\n'
    out += '}  // namespace ui_font\n'
    (ROOT / 'src/ui_font_data.h').write_text(out)
    print('Font faces:', faces)
    print('Antialiased glyph coverage:', len(pixels), 'bytes; glyphs:', len(glyphs))


if __name__ == '__main__':
    main()
