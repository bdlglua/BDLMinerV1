#!/usr/bin/env python3
"""Bake antialiased DejaVu Sans glyphs at native display sizes (Pillow only).
The firmware uses 4-bit coverage RLE directly from flash, without font loads,
glyph heap allocations or stretching a low-resolution bitmap font.
"""
from pathlib import Path
import argparse
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SIZES = (8, 9, 10, 11, 12, 14, 16, 18, 20, 24, 28, 32, 40)
CHARS = ''.join(chr(i) for i in range(32, 127))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, default=ROOT / 'assets/display/DejaVuSans.ttf')
    args = parser.parse_args()
    glyphs, pixels, faces = [], [], []
    for height in SIZES:
        size = height
        while True:
            font = ImageFont.truetype(str(args.font), size)
            _, top, _, bottom = font.getbbox(CHARS, anchor='ls')
            if bottom - top <= height or size == 1:
                break
            size -= 1
        baseline = -top + (height - (bottom - top)) // 2
        first = len(glyphs)
        for char in CHARS:
            left, _, right, _ = font.getbbox(char, anchor='ls')
            width = max(1, right - left)
            advance = max(1, math.ceil(font.getlength(char)))
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, baseline), char, font=font, fill=255, anchor='ls')
            data = image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()
            coverage = [(v * 15 + 127) // 255 for v in data]
            offset = len(pixels)
            for i in range(len(coverage)):
                if i and coverage[i] == coverage[i-1] and pixels[-1] >> 4 < 15:
                    pixels[-1] += 16
                else:
                    pixels.append(coverage[i])
            glyphs.append((offset, len(pixels) - offset, width, advance, left))
        faces.append((height, baseline, first))
    out = '// Generated by tools/pack_display_fonts.py; DejaVu license in assets/display/.\n#pragma once\n#include <stdint.h>\nnamespace ui_font {\n'
    out += 'struct Glyph { uint32_t offset; uint16_t length; uint8_t width, advance; int8_t left; };\n'
    out += 'constexpr Glyph kGlyphs[] = {\n' + ''.join('    {' + ','.join(map(str, g)) + '},\n' for g in glyphs) + '};\n'
    out += 'constexpr uint8_t kCoverage[] = {\n' + '\n'.join('    ' + ','.join(f'0x{v:02x}' for v in pixels[i:i+24]) + ',' for i in range(0, len(pixels), 24)) + '\n};\n'
    out += '#define BDL_FONT_FACES ' + ','.join('{' + str(first) + ',' + str(height) + ',' + str(baseline) + '}' for height, baseline, first in faces) + '\n'
    out += '}  // namespace ui_font\n'
    (ROOT / 'src/ui_font_data.h').write_text(out)
    print('Font faces:', faces)
    print('Antialiased glyph coverage:', len(pixels), 'bytes; glyphs:', len(glyphs))


if __name__ == '__main__':
    main()
